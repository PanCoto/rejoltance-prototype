import json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'game')
IMG = os.path.join(ROOT, 'img')
OUT = os.path.join(ROOT, 'img-index.js')
EXT = ('.webp', '.png', '.jpg', '.jpeg', '.gif', '.avif')
PAT = re.compile(r'^(\d+)(?:[_\-. ].*)?(\.[A-Za-z0-9]+)$')

found, dup = {}, []
for fn in sorted(os.listdir(IMG), key=lambda s: s.lower()):
    m = PAT.match(fn)
    if not m or m.group(2).lower() not in EXT:
        continue
    i = int(m.group(1))
    if i in found:
        dup.append((i, found[i], fn))
        continue
    found[i] = fn

cards = {}
src = open(os.path.join(ROOT, 'cards.js'), encoding='utf-8').read()
for m in re.finditer(r'Id:\s*(\d+),\s*Name:\s*"([^"]*)"', src):
    cards[int(m.group(1))] = m.group(2)

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/make_img_index.py - do not edit by hand. Maps card Id -> file in img/ (matched by the number at the start of the file name).\n')
    f.write('window.RJ_IMG=' + json.dumps({str(k): found[k] for k in sorted(found)}, indent=0, separators=(',', ':')).replace('\n', '') + ';\n')

print('img-index.js written: %d images' % len(found))
for i, a, b in dup:
    print('  WARNING: id %d has two files (%s, %s) - using %s' % (i, a, b, a))
no_art = [i for i in sorted(cards) if i not in found]
orphan = [i for i in sorted(found) if i not in cards]
if no_art:
    print('  cards without art (they show missing_texture): ' + ', '.join('%d %s' % (i, cards[i]) for i in no_art))
if orphan:
    print('  images that match no card in cards.js (fine if the card comes from cards-live.json): ' + ', '.join(found[i] for i in orphan))
