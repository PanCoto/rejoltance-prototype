#!/usr/bin/env python3
"""Bundles the card art (+ card frame) as data URIs -> deck-art.js, used ONLY by "Share as PNG".
Why: when the game is opened straight from disk (file://), browsers treat every local image as cross-origin and refuse to export
a canvas that used one; images that come from a data: URI are fine. On a web server (GitHub Pages) share.js uses the normal
img/ files and never loads this bundle.
Run from the game folder after adding/changing card art:  python3 tools/make_deck_art.py"""
import base64, json, os, re
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..'); IMG = os.path.join(ROOT, 'img')
src = open(os.path.join(ROOT, 'img-index.js'), encoding='utf-8').read()
idx = json.loads(re.search(r'RJ_IMG\s*=\s*(\{.*?\})\s*;?\s*$', src, re.S).group(1))
mime = lambda f: 'image/png' if f.lower().endswith('.png') else 'image/webp' if f.lower().endswith('.webp') else 'image/jpeg'
def uri(f):
    with open(os.path.join(IMG, f), 'rb') as fh: return 'data:%s;base64,%s' % (mime(f), base64.b64encode(fh.read()).decode())
out = {k: uri(v) for k, v in idx.items() if os.path.exists(os.path.join(IMG, v))}
out['frame'] = uri('CardFront.png'); out['missing'] = uri('missing_texture.webp')
with open(os.path.join(ROOT, 'deck-art.js'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tools/make_deck_art.py - card art as data URIs for "Share as PNG" when the game is opened from disk (file://).\n')
    f.write('window.RJ_ART=' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(out), 'images ->', round(os.path.getsize(os.path.join(ROOT, 'deck-art.js')) / 1e6, 2), 'MB')
