#!/usr/bin/env python3
"""Builds the card art as data URIs for "Share as PNG" when the game is opened
from disk (file://). Browsers refuse to export a canvas that used local files, so
there the art is read from these scripts instead of img/.

  deck-art.js      window.RJ_ART      = {frame, missing, <Id>: art ...}   (current game)
  deck-art-legacy.js  window.RJ_ART_EXP  = {<Id>: art ...}                   (Legacy art only)

The Legacy file only holds art from img/legacy/; the Legacy version loads
deck-art.js first and uses it as the fallback (same rule as CLFB in ui.js).
Needs Pillow (pip install pillow). Run from the project root:

  python tools/make_deck_art.py              # both
  python tools/make_deck_art.py legacy      # only deck-art-legacy.js
  python tools/make_deck_art.py current      # only deck-art.js
"""
import base64, io, json, os, re, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIZE = (260, 368)           # card art is stored at this size
EXT = ('.webp', '.png', '.jpg', '.jpeg')
NAME = re.compile(r'^(\d+)(?:_.*)?$')

def uri(img, fmt):
    b = io.BytesIO()
    if fmt == 'PNG':
        img.save(b, 'PNG', optimize=True)
    else:
        img.convert('RGB').save(b, 'WEBP', quality=80, method=6)
    return 'data:image/%s;base64,%s' % (fmt.lower(), base64.b64encode(b.getvalue()).decode())

def small(path):
    im = Image.open(path)
    im.load()
    if im.width > SIZE[0] or im.height > SIZE[1]:
        im.thumbnail(SIZE, Image.LANCZOS)
    return im

def arts(folder):
    out, path = {}, os.path.join(ROOT, folder)
    if not os.path.isdir(path):
        print('  (%s does not exist yet)' % folder)
        return out
    for f in sorted(os.listdir(path)):
        stem, ext = os.path.splitext(f)
        g = NAME.match(stem)
        if ext.lower() not in EXT or not g or not os.path.isfile(os.path.join(path, f)):
            continue
        i = g.group(1).lstrip('0') or '0'
        if i not in out:
            out[i] = uri(small(os.path.join(path, f)), 'WEBP')
    return dict(sorted(out.items(), key=lambda kv: int(kv[0])))

def write(name, header, var, d):
    with open(os.path.join(ROOT, name), 'w', encoding='utf-8', newline='') as fh:
        fh.write('// GENERATED by tools/make_deck_art.py - %s\n' % header)
        fh.write('window.%s=%s;\n' % (var, json.dumps(d, separators=(',', ':'))))
    print('%s: %d images, %.1f KB' % (name, len(d), os.path.getsize(os.path.join(ROOT, name)) / 1024))

def current():
    d = arts('img')
    d['frame'] = uri(Image.open(os.path.join(ROOT, 'img', 'CardFront.png')).convert('RGBA'), 'PNG')
    d['missing'] = uri(small(os.path.join(ROOT, 'img', 'missing_texture.webp')), 'WEBP')
    write('deck-art.js', 'card art as data URIs for "Share as PNG" when the game is opened from disk (file://).', 'RJ_ART', d)

def legacy():
    write('deck-art-legacy.js', 'Legacy card art as data URIs for "Share as PNG" when the game is opened from disk (file://).',
          'RJ_ART_EXP', arts(os.path.join('img', 'legacy')))

if __name__ == '__main__':
    args = sys.argv[1:] or ['current', 'legacy']
    for a in args:
        {'current': current, 'legacy': legacy}.get(a, lambda: sys.exit('unknown target %r (use: current, legacy)' % a))()
